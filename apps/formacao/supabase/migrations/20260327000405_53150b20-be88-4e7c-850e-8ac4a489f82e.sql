<h2 class="section-title">O rim artificial e o relacionamento impossível</h2>

<p>Dethlefsen faz uma observação sobre a diálise que é ao mesmo tempo precisa e perturbadora. Quando os rins param completamente e a diálise se torna necessária, o paciente troca o relacionamento humano pela máquina: aquele que foi incapaz de resolver seus problemas com um parceiro de carne e osso depara com a máquina perfeita como novo parceiro. Uma máquina que faz tudo que lhe é pedido sem nada exigir em troca.</p>

<p>Mas a contrapartida é total dependência: o paciente precisa comparecer à máquina regularmente e de forma absoluta — muito mais do que qualquer relação humana jamais exigiu. O paradoxo que o corpo criou é preciso: ao fugir da dependência relacional, acabou numa dependência muito mais absoluta.</p>

