<h2 class="section-title">Os rins como órgão do relacionamento</h2>

<p>Dethlefsen faz uma observação que abre toda a compreensão dos rins: eles representam, no corpo humano, o âmbito da convivência. As dores e afecções dos rins costumam surgir quando existem problemas de relacionamento e de convivência — não tanto de relações sexuais, mas da capacidade de relacionamento com os semelhantes em geral. A forma como a pessoa se relaciona com os outros manifesta-se com especial clareza nas relações conjugais ou de par, mas é comum a todas as relações.</p>

<p>Os rins são órgãos pares — e ele aponta que todos os órgãos pares no corpo humano têm relação com a temática do contato ou da convivência. Os pulmões representam o contato com o meio ambiente em geral. Os órgãos sexuais representam a relação erótica. E os rins correspondem à convivência com o semelhante — ao que os gregos chamavam <em>filia</em>, a amizade, o amor de igual para igual.</p>

