<h2 class="section-title">Os cálculos renais: o que ficou duro de tanto segurar</h2>

<p>A formação de cálculos renais é, para Dethlefsen, o equivalente físico dos cálculos biliares — só que com uma diferença de gênero estatisticamente significativa: cálculos biliares são mais comuns em mulheres, cálculos renais são mais comuns em homens.</p>

<p>A leitura é precisa: o homem tem maior dificuldade em encarar os temas da convivência e da harmonia do que a mulher, melhor dotada para lidar com tais princípios. Os cálculos renais seriam, portanto, a cristalização de temas relacionais não processados — questões de convivência, de parceria, de equilíbrio com o outro que foram sendo adiadas até endurecer.</p>

<p>O cálculo é composto de substâncias que deveriam ter sido eliminadas por não serem necessárias para o corpo. Isso corresponde, no plano psíquico, à acumulação de temas que o indivíduo há muito deveria ter colocado de parte por não serem necessários para seu desenvolvimento. Caso se insista em se agarrar a temas supérfluos e que tendem a se arrastar, estes acabam por bloquear a corrente do desenvolvimento e produzir congestão.</p>

<p>A cólica renal — a dor intensa da passagem do cálculo — ele compara a um parto: o corpo tentando expulsar, com esforço máximo, o que deveria ter ido há muito tempo. E o tratamento médico convencional descreve, com ironia simbólica, o que seria a solução psíquica: calor como expressão de amor e afeto, relaxamento dos vasos contraídos em sinal de receptividade, ingestão de líquidos para que tudo possa voltar a fluir.</p>

